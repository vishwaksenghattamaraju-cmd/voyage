COMMENT ON COLUMN public.trips.llm_provider IS 'Agent model provider used (e.g., rule-based, gemini, openai)';
COMMENT ON COLUMN public.trips.trip_data IS 'Complete structured itinerary JSON object including daily schedule, budget breakdown, and tips';
