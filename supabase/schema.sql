-- 1. Create the trips table if it does not already exist
CREATE TABLE IF NOT EXISTS public.trips (
    trip_id TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    destination TEXT NOT NULL DEFAULT '',
    duration_days INTEGER NOT NULL DEFAULT 1,
    budget TEXT NOT NULL DEFAULT '',
    companions TEXT NOT NULL DEFAULT '',
    climate TEXT NOT NULL DEFAULT '',
    llm_provider TEXT NOT NULL DEFAULT '',
    place_id TEXT DEFAULT '',
    location_context TEXT DEFAULT '',
    trip_data JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- 2. Idempotent column migrations (in case an older version of the table exists)
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS trip_id TEXT;
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now());
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS destination TEXT DEFAULT '';
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS duration_days INTEGER DEFAULT 1;
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS budget TEXT DEFAULT '';
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS companions TEXT DEFAULT '';
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS climate TEXT DEFAULT '';
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS llm_provider TEXT DEFAULT '';
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS place_id TEXT DEFAULT '';
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS location_context TEXT DEFAULT '';
ALTER TABLE public.trips ADD COLUMN IF NOT EXISTS trip_data JSONB DEFAULT '{}'::jsonb;

-- 3. Ensure primary key on trip_id safely
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'trips_pkey' AND conrelid = 'public.trips'::regclass
    ) THEN
        ALTER TABLE public.trips ADD PRIMARY KEY (trip_id);
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END $$;

-- 4. Create indexes for high-speed queries and sorting
CREATE INDEX IF NOT EXISTS idx_trips_created_at_desc ON public.trips (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_trips_destination ON public.trips (destination);
CREATE INDEX IF NOT EXISTS idx_trips_trip_data_gin ON public.trips USING gin (trip_data);

-- 5. Grant table permissions to Supabase PostgREST roles
GRANT ALL ON TABLE public.trips TO postgres, anon, authenticated, service_role;

-- 6. Enable Row Level Security (RLS)
ALTER TABLE public.trips ENABLE ROW LEVEL SECURITY;

-- 7. Clean up existing policies for clean, idempotent re-runs
DROP POLICY IF EXISTS "Allow public read access to trips" ON public.trips;
DROP POLICY IF EXISTS "Allow public insert access to trips" ON public.trips;
DROP POLICY IF EXISTS "Allow public update access to trips" ON public.trips;
DROP POLICY IF EXISTS "Allow public delete access to trips" ON public.trips;

-- 8. Grant policies for the public trip catalog
-- Note: When the backend uses SUPABASE_SERVICE_ROLE_KEY, PostgreSQL bypasses RLS automatically.
-- These policies ensure that if SUPABASE_ANON_KEY is used, operations still succeed.
CREATE POLICY "Allow public read access to trips"
    ON public.trips
    FOR SELECT
    TO anon, authenticated, service_role
    USING (true);

CREATE POLICY "Allow public insert access to trips"
    ON public.trips
    FOR INSERT
    TO anon, authenticated, service_role
    WITH CHECK (true);

CREATE POLICY "Allow public update access to trips"
    ON public.trips
    FOR UPDATE
    TO anon, authenticated, service_role
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow public delete access to trips"
    ON public.trips
    FOR DELETE
    TO anon, authenticated, service_role
    USING (true);

